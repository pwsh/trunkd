//! `Cargo.lock` → the dependency table the About page shows.
//!
//! This file is compiled **twice**: once by `build.rs` (via `#[path]`), which
//! uses it to turn the workspace lockfile into a static table baked into the
//! binary, and once by the crate itself, where its unit tests live. A build
//! script cannot host `#[test]`s of its own, and a lockfile parser that nobody
//! tests is a lockfile parser that silently reports an empty dependency list,
//! so the two share one source file rather than one being a copy of the other.
//!
//! Nothing here reaches outside `std` and `toml`; the crate side is otherwise
//! unused, hence the module-wide `dead_code` allowance.
#![allow(dead_code)]

/// One `[[package]]` entry, flattened to what the page renders.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockPackage {
    /// Crate name.
    pub name: String,
    /// Exact resolved version.
    pub version: String,
    /// Where it came from, already humanised: `"crates.io"`, a git URL with
    /// its locked revision, or `"path"` for a member of this workspace.
    pub source: String,
    /// Whether this is one of our own crates (no `source` key in the lock).
    pub workspace: bool,
}

/// Parse a `Cargo.lock`, newest format (v3/v4) or the older v1/v2 — every one
/// of them is a TOML array of `[[package]]` tables with the same three keys.
///
/// Unparsable input yields an empty list rather than an error: the About page
/// exists to help diagnose a deployment, and it must never be the reason a
/// build fails.
pub fn parse_lock(text: &str) -> Vec<LockPackage> {
    // A whole document parses as a `Table`; since toml 0.9 `Value: FromStr`
    // parses a single TOML *value* and would reject every lockfile.
    let Ok(doc) = text.parse::<toml::Table>() else {
        return Vec::new();
    };
    let Some(packages) = doc.get("package").and_then(toml::Value::as_array) else {
        return Vec::new();
    };
    let mut out: Vec<LockPackage> = packages
        .iter()
        .filter_map(|p| {
            let name = p.get("name")?.as_str()?.to_owned();
            let version = p.get("version")?.as_str()?.to_owned();
            let source = p.get("source").and_then(toml::Value::as_str);
            Some(LockPackage {
                name,
                version,
                workspace: source.is_none(),
                source: describe_source(source),
            })
        })
        .collect();
    // The lock is already sorted, but a v1 lock is not guaranteed to be, and a
    // table an operator reads should be in one predictable order.
    out.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    out
}

/// Humanise a lockfile `source` string.
///
/// * absent → `"path"`: a lock entry with no source is a workspace member.
/// * `registry+https://github.com/rust-lang/crates.io-index` → `"crates.io"`.
/// * `git+URL?rev=X#SHA` → `"git URL @ SHA"`, the full commit rather than the
///   requested rev, because the commit is what is actually in the binary.
fn describe_source(source: Option<&str>) -> String {
    let Some(src) = source else {
        return "path".to_owned();
    };
    if let Some(rest) = src.strip_prefix("registry+") {
        return if src.contains("crates.io-index") {
            "crates.io".to_owned()
        } else {
            format!("registry {rest}")
        };
    }
    if let Some(rest) = src.strip_prefix("git+") {
        let (url, sha) = match rest.split_once('#') {
            Some((url, sha)) => (url, Some(sha)),
            None => (rest, None),
        };
        // Drop the `?rev=`/`?branch=` selector: the locked commit after `#` is
        // the precise answer, and repeating the selector only adds noise.
        let url = url.split('?').next().unwrap_or(url);
        return match sha {
            Some(sha) => format!("git {url} @ {sha}"),
            None => format!("git {url}"),
        };
    }
    src.to_owned()
}

/// The generated Rust source for the embedded table.
///
/// A `&[(&str, &str, &str, bool)]` rather than a struct: the generated file is
/// `include!`d into a module that already declares the struct it feeds.
pub fn generate_table(packages: &[LockPackage]) -> String {
    let mut out = String::from(
        "// Generated by build.rs from the workspace Cargo.lock. Do not edit.\n\
         pub static DEPENDENCIES: &[(&str, &str, &str, bool)] = &[\n",
    );
    for p in packages {
        out.push_str(&format!(
            "    ({:?}, {:?}, {:?}, {}),\n",
            p.name, p.version, p.source, p.workspace
        ));
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A lockfile with one of each kind of source, in the v3 shape cargo
    /// writes today.
    const FIXTURE: &str = r#"
version = 3

[[package]]
name = "trunkd"
version = "0.0.1"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "5f0e2c6ed6606019b4e29e69dbaba95b11854410e5347d525002456dbbb786b6"

[[package]]
name = "some-fork"
version = "0.3.0"
source = "git+https://github.com/example/some-fork?rev=abc#abcdef0123456789"
"#;

    #[test]
    fn every_package_is_parsed_with_its_source_classified() {
        let pkgs = parse_lock(FIXTURE);
        assert_eq!(pkgs.len(), 3, "one entry per [[package]]: {pkgs:?}");

        let serde = pkgs.iter().find(|p| p.name == "serde").expect("serde");
        assert_eq!(serde.version, "1.0.219");
        assert_eq!(serde.source, "crates.io");
        assert!(!serde.workspace);

        let ours = pkgs.iter().find(|p| p.name == "trunkd").expect("trunkd");
        assert_eq!(ours.source, "path");
        assert!(ours.workspace, "no source key means a workspace member");

        let fork = pkgs.iter().find(|p| p.name == "some-fork").expect("fork");
        assert_eq!(
            fork.source, "git https://github.com/example/some-fork @ abcdef0123456789",
            "the locked commit, without the ?rev= selector"
        );
        assert!(!fork.workspace);
    }

    #[test]
    fn the_table_is_sorted_by_name_then_version() {
        let names: Vec<_> = parse_lock(FIXTURE).into_iter().map(|p| p.name).collect();
        assert_eq!(names, ["serde", "some-fork", "trunkd"]);
    }

    #[test]
    fn junk_is_an_empty_table_rather_than_a_failed_build() {
        assert!(parse_lock("this is not toml {{{").is_empty());
        assert!(parse_lock("").is_empty(), "no [[package]] at all");
        // A package missing the keys we need is skipped, not fatal.
        assert!(parse_lock("[[package]]\nname = \"x\"\n").is_empty());
    }

    #[test]
    fn the_generated_table_is_compilable_rust_with_one_row_per_package() {
        let src = generate_table(&parse_lock(FIXTURE));
        assert!(src.contains("pub static DEPENDENCIES"));
        assert!(src.contains(r#"("serde", "1.0.219", "crates.io", false)"#));
        assert!(src.contains(r#"("trunkd", "0.0.1", "path", true)"#));
        assert_eq!(src.matches("),\n").count(), 3);
    }
}
